size_t api_symbols_count(void)
{
    return sizeof(s_api_symbols) / sizeof(s_api_symbols[0]);
}

void api_symbols_link_all_public_functions(void)
{
    for (size_t i = 0; i < sizeof(s_api_symbols) / sizeof(s_api_symbols[0]); ++i) {
        if (!s_api_symbols[i].address) {
            printf("API_SYMBOL_ZERO|%s\n", s_api_symbols[i].name);
        }
    }
    printf("API_SYMBOLS_COUNT|%zu\n", api_symbols_count());
}
